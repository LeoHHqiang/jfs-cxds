const PROVINCE_ORDER = Object.keys(PRIMARY_REGIONS).filter((p) => p !== '其他')
PROVINCE_ORDER.sort((a, b) => a.localeCompare(b, 'zh-Hans-CN'))

/** 下拉：省（含「其他」） */
export const CN_PROVINCES = [...PROVINCE_ORDER, '其他']

export function citiesOfProvince(province) {
  if (!province || province === '其他') return Object.keys(PRIMARY_REGIONS.其他 || { 其他: [] })
  const m = PRIMARY_REGIONS[province]
  return m ? Object.keys(m).sort((a, b) => a.localeCompare(b, 'zh-Hans-CN')) : []
}

export function districtsOf(province, city) {
  if (!province || !city) return []
  if (province === '其他') return PRIMARY_REGIONS.其他[city] || []
  const m = PRIMARY_REGIONS[province]
  if (!m || !m[city]) return []
  return [...m[city]]
}

/** 去掉前导空白（含全角空格），便于「省 市 区 详细」中间带空格解析 */
function stripLeadingAddressWs(str) {
  return String(str || '').replace(/^[\s\u3000]+/, '')
}

/** 入库整行：省 + 市 + 区县 + 详细（不含国家前缀） */
export function composeAddressLine(parts) {
  const { province, city, district, detail } = parts || {}
  if (province === '其他') {
    const d = detail != null ? String(detail).trim() : ''
    return d
  }
  return [province, city, district, detail]
    .filter((x) => x != null && String(x).trim() !== '')
    .join('')
}

/**
 * 表格/展示用：省 市 区县 详细，分段空格；自动去掉历史数据中的「中国」前缀。
 */
export function formatToolUsageLocationDisplay(line) {
  const raw = line == null ? '' : String(line).trim()
  if (!raw) return '—'
  const p = parseToolUsageLine(raw)
  if (p.province === '其他') {
    const d = (p.detail || '').trim()
    return d || '—'
  }
  const parts = [p.province, p.city, p.district, (p.detail || '').trim()].filter(
    (x) => x != null && String(x).trim() !== '' && String(x).trim() !== '—'
  )
  if (parts.length) return parts.join(' ')
  let s = raw
  if (s.startsWith('中国')) s = s.slice(2).trim()
  return s || '—'
}

/**
 * 从整行地址还原省/市/区县/详细（用于编辑回显、Excel 单格导入等）。
 * 支持「浙江省宁波市江北区…」无空格，也支持省、市、区之间用空格或全角空格隔开；详细地址内可保留空格。
 */
export function parseToolUsageLine(line) {
  const empty = { province: '', city: '', district: '', detail: '' }
  if (line == null || String(line).trim() === '') {
    return { ...empty }
  }
  let s = String(line).trim()
  const out = { ...empty }
  if (s.startsWith('中国')) {
    s = stripLeadingAddressWs(s.slice(2))
  }
  const provinces = [...CN_PROVINCES].sort((a, b) => b.length - a.length)
  let matched = false
  for (const p of provinces) {
    if (p === '其他') continue
    if (s.startsWith(p)) {
      out.province = p
      s = stripLeadingAddressWs(s.slice(p.length))
      matched = true
      break
    }
  }
  if (!matched) {
    out.province = '其他'
    out.city = '其他'
    out.district = '—'
    out.detail = stripLeadingAddressWs(String(line).trim().replace(/^中国\s*/, ''))
    return out
  }
  const cities = citiesOfProvince(out.province).sort((a, b) => b.length - a.length)
  for (const c of cities) {
    if (s.startsWith(c)) {
      out.city = c
      s = stripLeadingAddressWs(s.slice(c.length))
      break
    }
  }
  const dists = districtsOf(out.province, out.city).sort((a, b) => b.length - a.length)
  for (const d of dists) {
    if (s.startsWith(d)) {
      out.district = d
      s = stripLeadingAddressWs(s.slice(d.length))
      break
    }
  }
  out.detail = s.trim()
  return out
}

